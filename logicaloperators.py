#logical operators combinne or reverse conditions.
# or and not are logical operators.
#in or condition if any one condition is true then it will return true.
print(10>5 or 5>10)
#and condition if all conditions are true then it will return true.
print(10>5 and 5>10)
#not condition if the condition is true then it will return false and vice versa.
print(not 10>5)